#include <stdint.h>
#include <stdlib.h>
#include <stdio.h>
#include <string.h>
#include <stdbool.h>
#include <assert.h>

//==================================================================================================
// Функция: bitmap_clear
// Назначение: Очищает большую битовую маску
//--------------------------------------------------------------------------------------------------
// Параметры:
// bits (in) - массив байт для битов большой битовой маски.
// size (in) - кол-во битов в битовой маске.
//
// Возвращаемое отсутствует
//
// Используемые внешние переменные:
// отсутствуют
//
// Примечания:
// - Память по указателю bits должна быть доступна на чтение на (size + 7)/8
//   элементов вперёд.
//==================================================================================================
void bitmap_clear(uint8_t* bits, uint32_t size)
{
    memset(bits, 0, (size + 7U)/8U);
}

//==================================================================================================
// Функция: bitmap_set
// Назначение: Устанавливает в 1 биты в большой битовой маске
//--------------------------------------------------------------------------------------------------
// Параметры:
// bits (in) - массив байт для битов большой битовой маски.
// size (in) - кол-во битов в битовой маске.
// from (in) - бит, начиная с которого в маске будут выставляться биты.
// to   (in) - бит, до которого будут выставляться биты (не включая его).
//
// Возвращаемое значение:
// Отсутствует
//
// Используемые внешние переменные:
// Отсутствуют
//
// Примечания:
// - Память по указателю bits должна быть доступна на чтение на (size + 7)/8
//   элементов вперёд.
// - Должно быть выполнено неравенство: from < to <= size 
//==================================================================================================
void bitmap_set(uint8_t* bits, uint32_t size, uint32_t from, uint32_t to)
{
    assert(from < to && to <= size);

    // Номер байта, в котором требуется выставить старшие биты.
    uint32_t fromByte = from / 8U;
    // Номер байта в котором требуется выставить младшие биты.
    uint32_t toByte = to / 8U;

    // Битовая маска, которую требуется применить к байту fromByte.
    uint8_t fromByteBitmask = (uint8_t) (0xFFU << (from % 8));

    // Битовая маска, которую требуется применить к байту toByte.
    uint8_t toByteBitmask = (uint8_t) (0xFFU >> (8 - (to % 8)));

    // Применяем битовую маску.
    if (fromByte != toByte)
    {
        bits[fromByte] |= fromByteBitmask;
        bits[toByte] |= toByteBitmask;
        
        for (uint32_t i = fromByte + 1U; i < toByte; ++i)
        {
            bits[i] = 0xFF;
        }
    }
    else
    {
        bits[fromByte] |= fromByteBitmask & toByteBitmask;
    }
}

//==================================================================================================
// Функция: bitmap_check
// Назначение: Проверяет наличие единиц в заданном диапозоне в большой битовой маске
//--------------------------------------------------------------------------------------------------
// Параметры:
// bits (in) - массив байт для битов большой битовой маски.
// size (in) - кол-во битов в битовой маске.
// from (in) - бит, начиная с которого в маске будут проверяться биты.
// to   (in) - бит, до которого будут проверяться биты (не включая его).
//
// Возвращаемое значение:
// true  - на позициях полуинтервала [from; to) присутствуют выставленные биты. 
// false - в противном случае.
//
// Используемые внешние переменные:
// отсутствуют
//
// Примечания:
// - Память по указателю bits должна быть доступна на чтение на (size + 7)/8
//   элементов вперёд.
// - Должно быть выполнено неравенство: from < to <= size 
//==================================================================================================
bool bitmap_check(uint8_t* bits, uint32_t size, uint32_t from, uint32_t to)
{
    assert(from < to && to <= size);
    
    // Номер байта, в котором требуется выставить старшие биты.
    uint32_t fromByte = from / 8U;
    // Номер байта в котором требуется выставить младшие биты.
    uint32_t toByte = to / 8U;

    // Битовая маска, которую требуется применить к байту fromByte.
    uint8_t fromByteBitmask = (uint8_t) (0xFFU << (from % 8));

    // Битовая маска, которую требуется применить к байту toByte.
    uint8_t toByteBitmask = (uint8_t) (0xFFU >> (8 - (to % 8)));

    if (fromByte != toByte)
    {
        if ((bits[fromByte] & fromByteBitmask) != 0U)
        {
            return true;
        }
        if ((bits[toByte] & toByteBitmask) != 0U)
        {
            return true;
        }

        for (uint32_t i = fromByte + 1U; i < toByte; ++i)
        {
            if (bits[i] != 0U)
            {
                return true;
            }
        }
    }
    else
    {
        if ((bits[fromByte] & (fromByteBitmask & toByteBitmask)) != 0U)
        {
            return true;
        }
    }

    return false;
}

//==================================================================================================
// Функция: bitmap_print
// Назначение: Производит печать большой битовой маски.
//--------------------------------------------------------------------------------------------------
// Параметры:
// bits (in) - массив байт для битов большой битовой маски.
// size (in) - кол-во битов в битовой маске.
//
// Возвращаемое значение: отсутствует
//
// Используемые внешние переменные:
// Отсутствуют
//
// Примечания:
// - Память по указателю bits должна быть доступна на чтение на (size + 7)/8
//   элементов вперёд.
//==================================================================================================
void bitmap_print(uint8_t* bits, uint32_t size)
{
    for (uint32_t byte = 0U; byte < size/8U; ++byte)
    {
        uint8_t mask = bits[byte];
        printf("%u%u%u%u%u%u%u%u",
            (mask & 0x01U) >> 0U, (mask & 0x02U) >> 1U,
            (mask & 0x04U) >> 2U, (mask & 0x08U) >> 3U,
            (mask & 0x10U) >> 4U, (mask & 0x20U) >> 5U,
            (mask & 0x40U) >> 6U, (mask & 0x80U) >> 7U);
    }

    for (uint8_t bit = 0U; bit < size % 8U; ++bit)
    {
        printf("%u", (bits[size/8U] >> bit) & 0x01U);
    }

    printf("\n");
}

#define BITMAP_SIZE 100U
#define BITMAP_ARRAY_SIZE ((BITMAP_SIZE + 7U)/8U)

#define BITMAP_DIVISOR 19U
#define BITMAP_STEP 7U

int main(void)
{
    // Массив под большую битовую маску.
    uint8_t bits[BITMAP_ARRAY_SIZE];

    // Инициализируем большую битовую маску.
    bitmap_clear(bits, BITMAP_SIZE);
    bitmap_print(bits, BITMAP_SIZE);

    // Последовательно заполняем части битовой маски.
    for (uint8_t step = 0U, part = 0U;
        step < BITMAP_DIVISOR;
        ++step, part = (part + BITMAP_STEP) % BITMAP_DIVISOR)
    {
        uint32_t from = (BITMAP_SIZE *       part) / BITMAP_DIVISOR;
        uint32_t to   = (BITMAP_SIZE * (part + 1)) / BITMAP_DIVISOR;

        // Проверяем наличие битов на тех местах, которые мы пытаемся выставить.
        if (bitmap_check(bits, BITMAP_SIZE, from, to))
        {
            printf("Bitmap already has bits [%u; %u)\n", from, to);
            return EXIT_FAILURE;
        }

        bitmap_set(bits, BITMAP_SIZE, from, to);
        bitmap_print(bits, BITMAP_SIZE);
    }

    return EXIT_SUCCESS;
}
